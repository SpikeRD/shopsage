def _run(statements: list[str]) -> None:
    """执行一批 DDL：在线走连接，**离线（`--sql`）走 `op.execute`**。

    ⚠️ 为什么必须分两种（本仓实测踩到）：`alembic upgrade head --sql` 是**离线模式**，
    此时 `op.get_bind()` 返回的是 `MockConnection` —— 它**没有** `exec_driver_sql`
    （那是真实 DBAPI 连接的方法），于是整个离线 SQL 生成会以
    `AttributeError: 'MockConnection' object has no attribute 'exec_driver_sql'` 结束。
    `tests/test_db_migrations.py::test_offline_sql_generation_does_not_need_database`
    与 `3.db-runbook` 的「不连库也能出 DDL」都依赖这条路径。

    离线可用的原因：本迁移的语句**没有绑定参数**（DDL 里的信息全是常量），
    所以 `op.execute()` 在离线模式下能直接把 SQL 文本写进 output buffer。
    """
    if op.get_context().as_sql:
        for statement in statements:
            op.execute(statement)
        return
    connection = op.get_bind()
    for statement in statements:
        connection.exec_driver_sql(statement)


def upgrade() -> None:
    """Upgrade schema."""
    _run(DDL)


def downgrade() -> None:
    """Downgrade schema."""
    _run(DOWNGRADE_DDL)
