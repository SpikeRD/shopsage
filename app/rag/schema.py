"""向量表的 DDL（唯一真相）：迁移、测试建表、脱机预览都从这里取语句。

为什么把 DDL 抽成模块而不是写在迁移文件里：

1. **迁移只跑一次，测试要跑很多次**。`tests/rag/` 需要一张与生产**同构**的表来跑真 SQL
   （关键词腿的 BM25 是写在 SQL 里的，用假库测等于什么都没测）。两处各写一份 DDL 必然漂移，
   而漂移的后果是「测试绿、生产红」。
2. **改维度是一件要读文档的事**。`vector(n)` 的 n 必须与 `EMBEDDING_DIM` / `RAG_VECTOR_DIM` 一致，
   把 `CREATE TABLE` 集中在一处，改的时候只有一处能改错。

两条与 `10.rag.md` 第 6 节第 1 条的**有意差异**（别当成写错了）：

* **表名是 `rag_documents` + `rag_chunks`**，不是文档里写的 `chunks`。文档只给了一张表，
  但「文档级元数据」与「片段级内容」的生命周期不同：增量重建时**文档级**要记指纹/版本/上次同步时间，
  **片段级**要能标失效。合成一张表会逼出「同一文档的元数据在 N 行里各存一份」的冗余，
  而冗余一定漂移（第 3 行的 updated_at 与第 7 行不一致时，谁是对的？）。
* **多了 `ngrams` / `ngram_tsv` / `ngram_doc` / `ngram_tokens` 四列**：中文全文检索的落点
  （见 `textkit.py` 的解释）。文档里的 `text / embedding / source / chunk_id / is_active / updated_at`
  六列**一个都没少**。
"""

from __future__ import annotations

import re
from collections.abc import Iterable
from typing import Any

DOCUMENTS_TABLE = "rag_documents"
CHUNKS_TABLE = "rag_chunks"
STATS_TABLE = "rag_corpus_stats"
NGRAM_FUNCTION = "rag_chunk_ngrams"
NGRAM_TRIGGER = "rag_chunks_ngram_tsv"

# ── HNSW vs IVFFlat（`10.rag.md` 第 6 节第 1 条写的是「IVFFlat/HNSW 索引」）──────
# 选 HNSW：IVFFlat 必须先有**数据**再建（它的聚类中心是拿现有向量训练出来的），
# 于是「先建索引、后灌数据」的流水线里它会退化成一个很差的索引，而正确的顺序
# （先灌够数据 → CREATE INDEX → 再灌剩下的）在运维上没人愿意维护。
# HNSW 没有训练阶段，空表建索引也正确，增量插入自动维护 —— 代价是建索引慢、内存占用高。
HNSW_M = 16
HNSW_EF_CONSTRUCTION = 64

# 建表维度：**迁移与本模块必须一致**（`alembic/versions/*_add_rag_vector_tables.py`）。
# 改这里 = 一次数据迁移：旧向量与新模型不相容，必须重建索引 + 重灌全部向量。
# `tests/rag/test_rag_migrations.py` 会读迁移文件对账，漂移会红。
VECTOR_DIM = 1024

# 本步建的三张表（导出成常量：`alembic/env.py` 要把它们排除在 autogenerate 之外）。
RAG_TABLES: tuple[str, ...] = (DOCUMENTS_TABLE, CHUNKS_TABLE, STATS_TABLE)


def create_statements(
    vector_dim: int,
    *,
    chunks_table: str = CHUNKS_TABLE,
    documents_table: str = DOCUMENTS_TABLE,
    stats_table: str = STATS_TABLE,
    function_name: str = NGRAM_FUNCTION,
    trigger_name: str = NGRAM_TRIGGER,
) -> list[str]:
    """建表 + 建索引 + 建触发器，按依赖顺序返回（**幂等**：全部 IF NOT EXISTS）。

    `vector_dim <= 0` 时抛错：`vector(0)` 在 pgvector 里是合法的（可以存空向量），
    于是「维度忘了配」会变成「库里全是零维向量」这种要读很久才发现的事故。
    宁可在建表前就报错，并把该改的三个地方写在报错里。

    表名 / 函数名可覆盖：测试要在真实开发库里建**同构**的临时表（`test_rag_chunks` 之类），
    用同一份 DDL 才有「测试测的就是生产结构」这层保证。
    """
    if vector_dim <= 0:
        raise ValueError(
            f"建向量表需要明确的维度，收到 {vector_dim}。请设置 RAG_VECTOR_DIM（与 EMBEDDING_DIM 一致，"
            "bge-m3 = 1024 / text-embedding-3-small = 1536），三处必须一起改："
            "① .env 的 EMBEDDING_DIM + RAG_VECTOR_DIM；② 迁移里的 vector(n)；③ 重灌全部向量。"
        )

    return [
        # pgvector 扩展：官方 pgvector/pgvector 镜像里已编译好，CREATE 是幂等的
        "create extension if not exists vector",
        f"""
        create table if not exists {documents_table} (
            doc_id         bigint generated by default as identity primary key,
            source         text        not null,
            category       text        not null default 'general',
            doc_hash       text        not null,
            chunk_strategy text        not null default 'auto',
            version        integer     not null default 1,
            chunk_count    integer     not null default 0,
            chunk_hashes   jsonb       not null default '{{}}'::jsonb,
            is_active      boolean     not null default true,
            created_at     timestamptz not null default now(),
            updated_at     timestamptz not null default now(),
            constraint {documents_table}_source_key unique (source)
        )
        """,
        f"""
        create table if not exists {chunks_table} (
            id            bigint generated by default as identity primary key,
            doc_id        bigint  not null references {documents_table}(doc_id) on delete cascade,
            chunk_id      text    not null,
            version       integer not null default 1,
            text          text    not null,
            embedding     vector({vector_dim}) not null,
            ngrams        text    not null,
            ngram_tsv     tsvector not null default ''::tsvector,
            ngram_doc     integer not null default 0,
            ngram_tokens  jsonb   not null default '[]'::jsonb,
            source        text    not null,
            section       text,
            page          integer,
            category      text    not null default 'general',
            content_hash  text    not null,
            is_active     boolean not null default true,
            created_at    timestamptz not null default now(),
            updated_at    timestamptz not null default now(),
            constraint {chunks_table}_unique_version unique (doc_id, chunk_id, content_hash)
        )
        """,
        # 检索永远带 `is_active`，所以两个索引都做成部分索引：
        # 失效的历史片段（增量更新留下的旧版本）不占索引，也不会被召回。
        f"""
        create index if not exists {chunks_table}_embedding_hnsw
            on {chunks_table} using hnsw (embedding vector_cosine_ops)
            with (m = {HNSW_M}, ef_construction = {HNSW_EF_CONSTRUCTION})
        """,
        f"create index if not exists {chunks_table}_ngram_gin on {chunks_table} using gin (ngram_tsv)",
        f"create index if not exists {chunks_table}_active_doc on {chunks_table} (doc_id) where is_active",
        f"create index if not exists {chunks_table}_source_active on {chunks_table} (source) where is_active",
        # 语料统计（N / avgdl）：BM25 的两个全局量。
        # 为什么不每次检索现算：`select count(*), avg(ngram_doc) from chunks where is_active`
        # 在 10 万片段时要扫全表，而它**每条查询都要用**。维护成本是每次 ingest 一次 upsert。
        f"""
        create table if not exists {stats_table} (
            singleton    boolean     primary key default true,
            docs         integer     not null default 0,
            chunks       integer     not null default 0,
            total_tokens bigint      not null default 0,
            updated_at   timestamptz not null default now(),
            constraint {stats_table}_singleton check (singleton)
        )
        """,
        f"insert into {stats_table} (singleton) values (true) on conflict do nothing",
        # 触发器：`ngram_tsv` / `ngram_doc` 必须与 `ngrams` 严格同源。
        # 为什么不用生成列（"更现代"的方案）：生成列要求表达式 immutable，
        # 而 `to_tsvector('simple', x)` 是 **stable**（依赖 default_text_search_config）。
        # 硬塞进去会得到一个「有时对、有时错」的索引 —— 那比慢更糟。
        #
        # ⚠️ 整块包在一个 `DO $$ ... $$` 里（而不是拆成三条 `op.execute`），
        # 因为 `op.execute()` 一次只吃一条语句，而函数体内部**有分号**。
        # 包成 DO 块后，语句边界就只由最外层的分号决定，迁移不需要先做 SQL 切分
        # （切分这件事本身很容易写错，见 §10.1 的坑）。
        f"""
        do $rag$
        begin
            execute $fn$
                create or replace function {function_name}() returns trigger
                language plpgsql as $body$
                begin
                    new.ngram_tsv := to_tsvector('simple', coalesce(new.ngrams, ''));
                    if new.ngrams is null or btrim(new.ngrams) = '' then
                        new.ngram_doc := 0;
                    else
                        new.ngram_doc := cardinality(
                            regexp_split_to_array(btrim(new.ngrams), '\\s+')
                        );
                    end if;
                    return new;
                end
                $body$
            $fn$;
        end
        $rag$
        """,
        f"drop trigger if exists {trigger_name} on {chunks_table}",
        f"""
        create trigger {trigger_name} before insert or update of ngrams on {chunks_table}
        for each row execute function {function_name}()
        """,
    ]


def drop_statements(
    *,
    chunks_table: str = CHUNKS_TABLE,
    documents_table: str = DOCUMENTS_TABLE,
    stats_table: str = STATS_TABLE,
    function_name: str = NGRAM_FUNCTION,
    trigger_name: str = NGRAM_TRIGGER,
    drop_extension: bool = False,
) -> list[str]:
    """删表（**测试与本地重置用**）。

    顺序：先触发器再函数再表 —— `drop table` 会自动带走它上面的触发器，
    但函数不会跟着走（`cascade` 也只是删依赖它的东西），漏掉会留下一堆 `rag_chunk_ngrams`。
    """
    statements = [
        f"drop table if exists {chunks_table} cascade",
        f"drop function if exists {function_name}() cascade",
        f"drop table if exists {stats_table} cascade",
        f"drop table if exists {documents_table} cascade",
    ]
    if drop_extension:
        statements.append("drop extension if exists vector")
    return statements


def create_schema(
    connection: Any,
    vector_dim: int,
    *,
    chunks_table: str = CHUNKS_TABLE,
    documents_table: str = DOCUMENTS_TABLE,
    stats_table: str = STATS_TABLE,
    function_name: str = NGRAM_FUNCTION,
    trigger_name: str = NGRAM_TRIGGER,
) -> list[str]:
    """在给定连接上建表（**幂等，不提交**）：迁移、测试建临时表、本地重置都走它。

    返回执行过的语句列表（便于日志与测试断言）。
    用 `exec_driver_sql` 而不是 `text()`：DDL 里有 `$$` 与 `\\s+`，
    走参数绑定会在别的驱动/版本上才炸（见 `migrations.py` 的说明）。
    """
    statements = create_statements(
        vector_dim,
        chunks_table=chunks_table,
        documents_table=documents_table,
        stats_table=stats_table,
        function_name=function_name,
        trigger_name=trigger_name,
    )
    for statement in statements:
        connection.exec_driver_sql(statement)
    return statements


def drop_rag_schema(
    connection: Any,
    *,
    chunks_table: str = CHUNKS_TABLE,
    documents_table: str = DOCUMENTS_TABLE,
    stats_table: str = STATS_TABLE,
    function_name: str = NGRAM_FUNCTION,
    trigger_name: str = NGRAM_TRIGGER,
    drop_extension: bool = False,
) -> list[str]:
    """删表（**不提交**）。测试的 teardown 与本地重置用它。"""
    statements = drop_statements(
        chunks_table=chunks_table,
        documents_table=documents_table,
        stats_table=stats_table,
        function_name=function_name,
        trigger_name=trigger_name,
        drop_extension=drop_extension,
    )
    for statement in statements:
        connection.exec_driver_sql(statement)
    return statements


def table_exists(connection: Any, table: str = CHUNKS_TABLE) -> bool:
    """表是否存在（不依赖 information_schema 的 schema 过滤，按 `to_regclass` 判断）。"""
    row = connection.exec_driver_sql(f"select to_regclass('public.{table}') is not null").scalar()
    return bool(row)


def current_vector_dim(connection: Any, table: str = CHUNKS_TABLE, column: str = "embedding") -> int | None:
    """读出表上 `vector(n)` 的 n。表不存在 / 列不存在 / 不是 vector 列时返回 `None`。

    这是「配置里的维度」与「建表维度」对账的唯一手段：`vector(0)` 合法，
    `vector(1024)` 与 `vector(768)` 在写库前都不会报错，只有**维度恰好相同但向量空间不同**
    才是静默事故 —— 所以至少要把「维度一致吗」变成一句能跑的自检。

    表名/列名做白名单校验后才拼进 SQL：它们来自本仓常量或测试夹具，不走用户输入；
    但「拼接就顺手加一道校验」的成本是零，而一旦将来有人把它接到配置上，这道校验就救命了。
    """
    for value in (table, column):
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", value):
            raise ValueError(f"表名/列名只允许标识符字符，收到 {value!r}")

    # pgvector 把维度存在 atttypmod 里（与 varchar(n) 同一个机制）
    raw = connection.exec_driver_sql(
        "select atttypmod from pg_attribute "
        f"where attrelid = to_regclass('public.{table}') and attname = '{column}'"
    ).scalar()
    if raw is None:
        return None
    return int(raw) if int(raw) > 0 else None


def split_statements(sql: str) -> list[str]:
    """把一段多语句 SQL 按分号切成单条，**忽略 `$$`/`$tag$` 引用块内的分号**。

    为什么需要它：`op.execute()` 一次只吃一条语句（驱动层不接受多语句），
    而 `create_statements()` 里既有普通 DDL 也有 `DO $$ ... $$` 块，
    后者的**块内分号不能当语句边界**。天真地 `sql.split(";")` 会把块切碎 ——
    症状是「迁移跑到一半报语法错误」，而错的那一半看起来完全正常。

    实现上先把 dollar-quote 块**整体摘出来占位**，切完再放回去 ——
    比在字符流里手写状态机简单，也不会被块里的引号/反斜杠坑到。
    本仓 DDL 里的 dollar 标签都不嵌套（`$rag$` 里嵌 `$fn$` 里嵌 `$body$`），
    所以「非贪婪 + 取最短闭合」是安全的；一旦出现同名嵌套标签，这里必须先改。
    """
    blocks: list[str] = []
    pattern = re.compile(r"\$([A-Za-z_][A-Za-z0-9_]*)?\$.*?\$\1\$", re.DOTALL)

    def stash(match: re.Match[str]) -> str:
        blocks.append(match.group(0))
        return f"\x00RAGBLOCK{len(blocks) - 1}\x00"

    masked = pattern.sub(stash, sql)
    statements: list[str] = []
    for chunk in masked.split(";"):
        restored = chunk
        for index, block in enumerate(blocks):
            restored = restored.replace(f"\x00RAGBLOCK{index}\x00", block)
        if restored.strip():
            statements.append(restored.strip())
    return statements


